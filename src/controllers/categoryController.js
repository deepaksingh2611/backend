/**
 * GET /api/categories/:categoryId
 */
async function getCategoryDetail(req, res) {
  try {
    const rawId = (req.params.categoryId || '').trim().toLowerCase();
    let categoryKey = rawId.replace(/[^a-z0-9_]/g, '');
    if (ALIAS_MAP[categoryKey]) {
      categoryKey = ALIAS_MAP[categoryKey];
    }
    const data = CATEGORIES_DATA[categoryKey];

    if (!data) {
      return res.status(404).json({
        success: false,
        message: `Category '${categoryKey}' not found.`,
      });
    }

    return res.status(200).json({
      success: true,
      data: {
        category: {
          id: data.id,
          name: data.name,
          description: data.description,
        },
        subcategories: data.subcategories,
        popularStores: data.popularStores,
        bestDeals: enrichAndSortBestDeals(data.bestDeals || []),
        offers: data.offers || [],
        coupons: data.coupons || [],
      },
    });
  } catch (error) {
    console.error('Error in getCategoryDetail:', error);
    return res.status(500).json({
      success: false,
      message: 'Failed to fetch category detail.',
      error: error.message,
    });
  }
}

/**
 * GET /api/categories/:categoryId/subcategories/:subcategoryId
 */
async function getSubcategoryDetail(req, res) {
  try {
    let categoryId = (req.params.categoryId || '').trim().toLowerCase().replace(/[^a-z0-9_]/g, '');
    let subcategoryId = (req.params.subcategoryId || '').trim().toLowerCase().replace(/[^a-z0-9_]/g, '');
    if (ALIAS_MAP[categoryId]) {
      categoryId = ALIAS_MAP[categoryId];
    }
    const key = `${categoryId}-${subcategoryId}`;

    const data = SUBCATEGORIES_DATA[key];

    // Only curated subcategories have product data here. Returning the whole
    // category (or Fashion > Clothing) for any other subcategory showed wrong
    // products, so let the app use its own category-mapped catalog instead.
    if (!data) {
      return res.status(404).json({
        success: false,
        message: `Subcategory '${subcategoryId}' of '${categoryId}' not found.`,
      });
    }

    // Support query filters if passed (?filter=Shirts&style=Casual)
    let filteredProducts = [...(data.products || [])];
    const filterQuery = (req.query.filter || '').trim().toLowerCase();
    const styleQuery = (req.query.style || '').trim().toLowerCase();

    if (filterQuery && filterQuery !== 'all') {
      filteredProducts = filteredProducts.filter((p) => {
        return (
          (p.subcategoryId && p.subcategoryId.toLowerCase() === filterQuery) ||
          (p.gender && p.gender.toLowerCase() === filterQuery)
        );
      });
    }

    if (styleQuery && styleQuery !== 'all') {
      filteredProducts = filteredProducts.filter((p) => {
        return p.style && p.style.toLowerCase() === styleQuery;
      });
    }

    return res.status(200).json({
      success: true,
      data: {
        subcategory: data.subcategory,
        filters: data.filters || ['All'],
        subFilters: data.subFilters || {},
        products: enrichAndSortBestDeals(filteredProducts),
        stores: data.stores || [],
        offers: data.offers || [],
        coupons: data.coupons || [],
      },
    });
  } catch (error) {
    console.error('Error in getSubcategoryDetail:', error);
    return res.status(500).json({
      success: false,
      message: 'Failed to fetch subcategory detail.',
      error: error.message,
    });
  }
}

/**
 * GET /api/products/:productId/compare
 */
async function compareProduct(req, res) {
  try {
    const { productId } = req.params;
    const rawComparison =
      PRODUCT_COMPARISONS_DB[productId] || PRODUCT_COMPARISONS_DB['prod-shirt-1'];

    const { stores, bestStore } = compareAndPickBestStore(
      rawComparison.stores,
      rawComparison.product.originalPrice,
      rawComparison.product.category
    );

    return res.status(200).json({
      success: true,
      data: {
        ...rawComparison,
        stores,
        bestStore,
      },
    });
  } catch (error) {
    console.error('Error in compareProduct:', error);
    return res.status(500).json({
      success: false,
      message: 'Failed to compare product.',
      error: error.message,
    });
  }
}

