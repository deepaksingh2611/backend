/**
 * GET /api/home
 * Returns complete structured home discovery feed
 */
async function getHomeData(req, res) {
  try {
    // Automatically run Smart Price Comparison, Coupon Optimizer, and Savings Engine to rank best deals
    const optimizedBestDeals = enrichAndSortBestDeals(HOME_DATA.bestDeals);

    const responseData = {
      ...HOME_DATA,
      bestDeals: optimizedBestDeals,
    };

    return res.status(200).json({
      success: true,
      message: 'Home discovery data fetched successfully with smart best deals.',
      data: responseData,
    });
  } catch (error) {
    console.error('Error in getHomeData:', error);
    return res.status(500).json({
      success: false,
      message: 'Failed to fetch home data.',
      error: error.message,
    });
  }
}

